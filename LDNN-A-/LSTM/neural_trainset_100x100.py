def compute_away(former_point_x,former_point_y,chosen_point_x,chosen_point_y,goal_x,goal_y)->float:
    heuristic = math.sqrt((former_point_x - goal_x) ** 2 + (former_point_y - goal_y) ** 2)
    AwayFromFormer = math.sqrt((chosen_point_x - former_point_x) ** 2 + (chosen_point_y - former_point_y) ** 2) / heuristic if heuristic>1e-6 else 0.0
    return AwayFromFormer

def compute_prox(chosen_point_x,chosen_point_y,start_x,start_y,goal_x,goal_y)->float:
    dg = math.sqrt((chosen_point_x - goal_x) ** 2 + (chosen_point_y - goal_y) ** 2)
    ds = math.sqrt((chosen_point_x - start_x) ** 2 + (chosen_point_y - start_y) ** 2)
    proximity_score = 1 - dg / (ds + dg) if ds+dg>1e-6 else 0.0
    return proximity_score

